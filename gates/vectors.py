"""gates/vectors.py — the codec vectors are immutable under an unchanged tag (CODEC-28 (d), GATES-13).

gates/codec-vectors.tsv (`site<TAB>vector<TAB>tag<TAB>bytes<TAB>decoded`) is generated by `lake exe codec-vectors`,
whose `--check` proves the pinned bytes decode to the pinned text under each site's CURRENT tag. That cannot
see a hand edit that rewrites a same-tag row's text (or bytes) to a relabelled meaning: the edited row checks.
So, against the parent's table: for every (site, tag) present in both, the rows must be the same rows, byte for
byte — none changed, none removed, none added. A site whose tag moved is re-drawn freely (--write does that).
Red by name otherwise. No parent table (or no candidate table) = nothing to compare.
"""
from __future__ import annotations

import os

TABLE = os.path.join("gates", "codec-vectors.tsv")


def rows(root: str) -> dict[tuple[str, str], dict[str, str]] | None:
    """(site, tag) -> {vector: whole line}; None when the table is absent."""
    p = os.path.join(root, TABLE)
    if not os.path.isfile(p):
        return None
    out: dict[tuple[str, str], dict[str, str]] = {}
    for line in open(p, encoding="utf-8"):
        if not line.strip() or line.startswith("#"):
            continue
        f = line.rstrip("\n").split("\t")
        if len(f) < 3:
            out.setdefault(("?", "?"), {})[line] = line  # malformed; codec-vectors --check names it
            continue
        out.setdefault((f[0], f[2]), {})[f[1]] = line.rstrip("\n")
    return out


def check(root: str, base: str | None) -> list[str]:
    if not base:
        return []
    old, new = rows(base), rows(root)
    if old is None or new is None:
        return []
    red = []
    for key in sorted(set(old) & set(new)):
        site, tag = key
        a, b = old[key], new[key]
        for v in sorted(set(a) | set(b)):
            if v not in b:
                red.append(f"{TABLE}: {site} vector {v} removed under its unchanged tag {tag[:12]}")
            elif v not in a:
                red.append(f"{TABLE}: {site} vector {v} added under its unchanged tag {tag[:12]}")
            elif a[v] != b[v]:
                red.append(f"{TABLE}: {site} vector {v} edited under its unchanged tag {tag[:12]}: "
                           f"{a[v].split(chr(9), 4)[-1][:60]!r} -> {b[v].split(chr(9), 4)[-1][:60]!r} "
                           "(a change of meaning needs a new tag: rename the refinement)")
    return red
